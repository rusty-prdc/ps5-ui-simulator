function paintIcons(root = document) {
  root.querySelectorAll('[data-ico]').forEach(el => {
    const name = el.getAttribute('data-ico');
    if (ICONS[name]) el.innerHTML = `<svg viewBox="0 0 24 24">${ICONS[name]}</svg>`;
    el.removeAttribute('data-ico');
  });
}
